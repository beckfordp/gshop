function hashString(value: string): number {
  let hash = 0;
  for (let i = 0; i < value.length; i += 1) {
    hash = (hash * 31 + value.charCodeAt(i)) >>> 0;
  }
  return hash;
}

export function imageForSku(sku: string): string {
  const index = SKU_ORDER.indexOf(sku);
  if (index === -1) {
    return WATCH_IMAGES[hashString(sku) % WATCH_IMAGES.length];
  }
  return WATCH_IMAGES[index % WATCH_IMAGES.length];
}
